"""Write the sandbox operation logs the competition asks for as "execution evidence".

    python -m app.scripts.export_evidence                  # needs a running API with fresh demo data
    python -m app.scripts.export_evidence --tamper         # also records Verify FAIL then PASS

Replays the 14-step demo against the API, then saves what happened into submission/evidence/:

    sandbox_operation_log.txt   the demo transcript, one line per check (OK or FAIL)
    audit_log.json              every audit event, oldest first, with its hashes
    audit_verify.json           the hash-chain verification result
    payments.json               the payments with their tracker timelines and UETR
    bank_network.json           the simulated bank transfers with every hop, message and journal,
                                and the trial balance that proves the books balance
    smart_escrow.json           the escrows with their on-chain proof, the audit anchors and the
                                check that the database still matches the chain
    tamper_demo.json            (with --tamper) Verify after an edit, and after restoring it
    README.md                   what each file is

Everything is synthetic: simulated accounts, simulated providers, no real money. No password,
token, MFA code or webhook secret is written (the tests check that).
"""

from __future__ import annotations

import argparse
import json
import sys
from collections.abc import Callable
from pathlib import Path
from typing import Any

import httpx

from app.core.config import DEFAULT_DEMO_PASSWORD, DEFAULT_SANDBOX_MFA_CODE, get_settings
from app.core.db import Database
from app.scripts.demo_flow import DemoFlow
from app.scripts.tamper_audit import restore_row, tamper_row

DEFAULT_OUT = Path(__file__).resolve().parents[3] / "submission" / "evidence"
PAGE = 100

README = """# Execution evidence (sandbox operation logs)

Generated by `python -m app.scripts.export_evidence`. Everything here is **synthetic**: simulated
accounts, simulated providers, simulated settlement. No real money moved and no real data is used.

| File | What it shows |
|------|---------------|
| `sandbox_operation_log.txt` | The 14-step demo run against the API, one line per check, OK or FAIL |
| `audit_log.json` | Every audit event in order, each with `prev_event_hash` and `this_event_hash` |
| `audit_verify.json` | The hash-chain verification: status, events checked, head hash |
| `payments.json` | The payments created, with their state timeline and UETR |
| `bank_network.json` | The simulated interbank transfers (national and international) with every hop, the simulated messages and the double-entry journals, plus the trial balance and mirror-account check |
| `smart_escrow.json` | The smart escrows (schedule, state, the contract call log with its hashes), the simulated chain's status, the audit anchors written to it and the check that the database still matches the chain |
| `tamper_demo.json` | Verify after one audit row was edited behind the application's back (FAIL at that sequence), and after it was restored (PASS). Only present when run with `--tamper` |

To reproduce: start the API with fresh demo data, then run the command above.
"""


def _audit_events(flow: DemoFlow) -> list[dict[str, Any]]:
    events: list[dict[str, Any]] = []
    cursor: int | None = None
    while True:
        query = f"/audit/events?limit={PAGE}" + (f"&cursor={cursor}" if cursor else "")
        page = flow.fetch(query, "admin")
        events.extend(page["items"])
        cursor = page["next_cursor"]
        if cursor is None:
            return list(reversed(events))  # oldest first, so the chain reads in order


def _payments_with_trackers(flow: DemoFlow) -> list[dict[str, Any]]:
    listing = flow.fetch("/payments?limit=50", "parent")["items"]
    out = []
    for brief in listing:
        tracker = flow.fetch(f"/payments/{brief['payment_id']}/tracker", "parent")
        out.append({"payment": brief, "tracker": tracker})
    return out


def _bank_network(flow: DemoFlow) -> dict[str, Any]:
    """The simulated interbank transfers in full, and proof that the books balance."""
    network = flow.fetch("/bank/network", "admin")
    listing = flow.fetch("/bank/transfers?limit=50", "admin")["items"]
    transfers = [flow.fetch(f"/bank/transfers/{t['id']}", "admin") for t in reversed(listing)]
    keys = ("all_ok", "trial_balance", "mirror_accounts", "accounts_not_matching_entries")
    return {"network": {key: network[key] for key in keys}, "transfers": transfers}


def _smart_escrow(flow: DemoFlow) -> dict[str, Any]:
    """The escrows with their on-chain proof, the audit anchors and the anchor check."""
    return {
        "escrows": flow.fetch("/escrows", "parent")["items"],
        "chain": flow.fetch("/chain/status", "admin"),
        "anchors": flow.fetch("/chain/anchors", "admin")["items"],
        "anchor_check": flow.fetch("/chain/verify", "admin"),
    }


def _write(path: Path, data: Any) -> None:
    path.write_text(json.dumps(data, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")


def collect_evidence(
    client: httpx.Client,
    out_dir: Path,
    *,
    password: str,
    mfa_code: str,
    wait: Callable[[float], None],
    say: Callable[[str], None] = print,
    tamper_db: Path | None = None,
) -> list[str]:
    """Run the demo and write the evidence files. Returns the list of failed checks."""
    lines: list[str] = []

    def record(line: str) -> None:
        lines.append(line)
        say(line)

    flow = DemoFlow(client, password=password, mfa_code=mfa_code, wait=wait, say=record)
    failures = flow.run()
    out_dir.mkdir(parents=True, exist_ok=True)
    (out_dir / "sandbox_operation_log.txt").write_text("\n".join(lines) + "\n", encoding="utf-8")
    events = _audit_events(flow)
    _write(out_dir / "audit_log.json", {"events": events, "count": len(events)})
    verify = flow.fetch("/audit/verify", "admin")
    _write(out_dir / "audit_verify.json", verify)
    _write(out_dir / "payments.json", _payments_with_trackers(flow))
    _write(out_dir / "bank_network.json", _bank_network(flow))
    _write(out_dir / "smart_escrow.json", _smart_escrow(flow))
    if tamper_db is not None:
        change = tamper_row(tamper_db, max(1, len(events) - 1))
        broken = flow.fetch("/audit/verify", "admin")
        restore_row(tamper_db)
        fixed = flow.fetch("/audit/verify", "admin")
        _write(
            out_dir / "tamper_demo.json",
            {
                "edited_event": {"seq": change["seq"], "column": change["column"]},
                "verify_after_edit": broken,
                "verify_after_restore": fixed,
            },
        )
        if broken["status"] != "FAIL" or fixed["status"] != "PASS":
            failures.append(
                "tamper demo: Verify did not FAIL after the edit and PASS after restore"
            )
    (out_dir / "README.md").write_text(README, encoding="utf-8")
    return failures


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawTextHelpFormatter
    )
    parser.add_argument("--base-url", default="http://127.0.0.1:8000")
    parser.add_argument("--out", type=Path, default=DEFAULT_OUT)
    parser.add_argument("--password", default=DEFAULT_DEMO_PASSWORD)
    parser.add_argument("--mfa-code", default=DEFAULT_SANDBOX_MFA_CODE)
    parser.add_argument("--tamper", action="store_true", help="also record Verify FAIL, then PASS")
    args = parser.parse_args(argv)
    import time

    db_file = None
    if args.tamper:
        db_file = Path(Database(get_settings().database_url).sqlite_path())
    with httpx.Client(base_url=args.base_url, timeout=20.0) as client:
        try:
            failures = collect_evidence(
                client, args.out, password=args.password, mfa_code=args.mfa_code,
                wait=time.sleep, tamper_db=db_file,
            )  # fmt: skip
        except (RuntimeError, httpx.HTTPError) as exc:
            print(f"\nCould not export evidence: {exc}", file=sys.stderr)
            return 2
    if failures:
        print(f"\n{len(failures)} check(s) failed; evidence written anyway:", file=sys.stderr)
        for failure in failures:
            print(f"  - {failure}", file=sys.stderr)
        return 1
    print(f"\nEvidence written to {args.out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
