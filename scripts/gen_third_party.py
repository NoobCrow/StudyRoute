"""Generate docs/THIRD_PARTY.md: the licence of every direct dependency.

    python scripts/gen_third_party.py

Run it with the backend's Python environment (the packages must be installed there) after
`npm ci` in web/. Python licences come from the installed package metadata, JavaScript
licences from web/package-lock.json. Only direct dependencies are listed; transitive ones
are covered by the lock files.
"""

from __future__ import annotations

import json
import re
import sys
from importlib import metadata
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "docs" / "THIRD_PARTY.md"
NAME = re.compile(r"^[A-Za-z0-9_.-]+")


def python_license(dist: metadata.Distribution) -> str:
    expression = dist.metadata.get("License-Expression")
    if expression:
        return str(expression)
    tags = dist.metadata.get_all("Classifier") or []
    classifiers = [c.split(" :: ")[-1] for c in tags if "License ::" in c]
    if classifiers:
        return " / ".join(classifiers)
    declared = (dist.metadata.get("License") or "").strip()
    return declared if 0 < len(declared) <= 60 else "see package metadata"


def python_rows(requirements: Path) -> list[tuple[str, str, str]]:
    rows = []
    for line in requirements.read_text(encoding="utf-8").splitlines():
        line = line.strip()
        if not line or line.startswith(("#", "-r")):
            continue
        match = NAME.match(line)
        if match is None:
            raise SystemExit(f"Cannot read a package name from: {line}")
        dist = metadata.distribution(match.group())
        rows.append((dist.metadata["Name"], dist.version, python_license(dist)))
    return sorted(rows, key=lambda r: r[0].lower())


def javascript_rows(
    folder: str = "web",
) -> tuple[list[tuple[str, str, str]], list[tuple[str, str, str]]]:
    package = json.loads((ROOT / folder / "package.json").read_text(encoding="utf-8"))
    lock = json.loads((ROOT / folder / "package-lock.json").read_text(encoding="utf-8"))

    def rows(names: dict[str, str]) -> list[tuple[str, str, str]]:
        out = []
        for name in sorted(names):
            entry = lock["packages"][f"node_modules/{name}"]
            out.append((name, entry["version"], str(entry.get("license", "see package"))))
        return out

    return rows(package.get("dependencies", {})), rows(package.get("devDependencies", {}))


def table(rows: list[tuple[str, str, str]]) -> list[str]:
    lines = ["| Package | Version | Licence |", "|---------|---------|---------|"]
    lines += [f"| {name} | {version} | {licence} |" for name, version, licence in rows]
    return lines


