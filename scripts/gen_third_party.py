"""Generate docs/THIRD_PARTY.md: the licence of every direct dependency.

    python scripts/gen_third_party.py

Run it with the backend's Python environment (the packages must be installed there) after
`npm ci` in frontend/. Python licences come from the installed package metadata, JavaScript
licences from frontend/package-lock.json. Only direct dependencies are listed; transitive ones
are covered by the lock files.
"""

from __future__ import annotations

import json
import re
import sys
from importlib import metadata
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "docs" / "THIRD_PARTY.md"
NAME = re.compile(r"^[A-Za-z0-9_.-]+")


def python_license(dist: metadata.Distribution) -> str:
    expression = dist.metadata.get("License-Expression")
    if expression:
        return str(expression)
    tags = dist.metadata.get_all("Classifier") or []
    classifiers = [c.split(" :: ")[-1] for c in tags if "License ::" in c]
    if classifiers:
        return " / ".join(classifiers)
    declared = (dist.metadata.get("License") or "").strip()
    return declared if 0 < len(declared) <= 60 else "see package metadata"


def python_rows(requirements: Path) -> list[tuple[str, str, str]]:
    rows = []
    for line in requirements.read_text(encoding="utf-8").splitlines():
        line = line.strip()
        if not line or line.startswith(("#", "-r")):
            continue
        match = NAME.match(line)
        if match is None:
            raise SystemExit(f"Cannot read a package name from: {line}")
        dist = metadata.distribution(match.group())
        rows.append((dist.metadata["Name"], dist.version, python_license(dist)))
    return sorted(rows, key=lambda r: r[0].lower())


def javascript_rows(
    folder: str = "frontend",
) -> tuple[list[tuple[str, str, str]], list[tuple[str, str, str]]]:
    package = json.loads((ROOT / folder / "package.json").read_text(encoding="utf-8"))
    lock = json.loads((ROOT / folder / "package-lock.json").read_text(encoding="utf-8"))

    def rows(names: dict[str, str]) -> list[tuple[str, str, str]]:
        out = []
        for name in sorted(names):
            entry = lock["packages"][f"node_modules/{name}"]
            out.append((name, entry["version"], str(entry.get("license", "see package"))))
        return out

    return rows(package.get("dependencies", {})), rows(package.get("devDependencies", {}))


def table(rows: list[tuple[str, str, str]]) -> list[str]:
    lines = ["| Package | Version | Licence |", "|---------|---------|---------|"]
    lines += [f"| {name} | {version} | {licence} |" for name, version, licence in rows]
    return lines


def main() -> int:
    runtime = python_rows(ROOT / "backend" / "requirements.in")
    dev = python_rows(ROOT / "backend" / "requirements-dev.in")
    runtime_names = {r[0].lower() for r in runtime}
    dev = [r for r in dev if r[0].lower() not in runtime_names]
    js_runtime, js_dev = javascript_rows()
    _, contracts_dev = javascript_rows("contracts")
    lines = [
        "# Third-party components and licences",
        "",
        "Generated by `python scripts/gen_third_party.py`. Do not edit by hand.",
        "",
        "StudyRoute's own code is original work by the team. It uses the open-source components",
        "below, each under its own licence, and no third-party data set. The exchange rates,",
        "providers, fees, people and accounts in the sandbox are invented by the team. The",
        "competition rules require third-party components to be properly licensed; this is the",
        "inventory. Only direct dependencies are listed; the exact versions of everything",
        "installed are pinned in `backend/requirements.txt`, `frontend/package-lock.json` and",
        "`contracts/package-lock.json`.",
        "",
        "## Backend runtime (Python 3.12)",
        "",
        *table(runtime),
        "",
        "## Backend tooling (tests and lint)",
        "",
        *table(dev),
        "",
        "## Frontend runtime",
        "",
        *table(js_runtime),
        "",
        "## Frontend tooling (build and tests)",
        "",
        *table(js_dev),
        "",
        "## Smart-contract build tools (`contracts/`, development only)",
        "",
        "The backend runs the committed, compiled contracts and never installs these.",
        "",
        *table(contracts_dev),
        "",
        "## Notes",
        "",
        "- Fonts: Inter, Source Serif 4 and JetBrains Mono ship with the `@fontsource-variable`",
        "  packages above (SIL Open Font License 1.1). They are self-hosted: nothing is loaded",
        "  from the internet.",
        "- `py-evm` (an in-memory EVM) and `eth-abi` run the sandbox chain; both are pinned.",
        "- The Solidity contracts in `contracts/src/` are the team's own (MIT licence headers).",
        "- Images: only the team's own favicon and screenshots of the application.",
        "- A project licence for StudyRoute itself is the team's decision and is not set here.",
    ]
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(
        f"Wrote {OUT.relative_to(ROOT)}: {len(runtime)} + {len(dev)} Python, "
        f"{len(js_runtime)} + {len(js_dev)} JavaScript packages."
    )
    return 0


if __name__ == "__main__":
    sys.exit(main())
