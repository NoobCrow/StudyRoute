"""Generate docs/TEST_CASES.md from the blueprint test table and the real test suite.

    python scripts/gen_test_cases.py             # collects and runs the backend tests
    python scripts/gen_test_cases.py --no-run    # collect only (no pass count)

Run it with the backend's Python environment (pytest installed). The table of scenarios T01 to
T24 comes from docs/BLUEPRINT.md section 16; each row lists the tests that implement it.
"""

from __future__ import annotations

import argparse
import json
import re
import shutil
import subprocess
import sys
import tempfile
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
BACKEND = ROOT / "backend"
OUT = ROOT / "docs" / "TEST_CASES.md"
ROW = re.compile(r"^\| (T\d\d)\s+\| (.+?)\s+\| (.+?)\s+\| (.+?)\s+\|$", re.M)
TEST_ID = re.compile(r"test_(T\d\d)_")


def blueprint_scenarios() -> list[tuple[str, str, str, str]]:
    text = (ROOT / "docs" / "BLUEPRINT.md").read_text(encoding="utf-8")
    # The Markdown source escapes the dot, so the heading reads "16\. Test plan ...".
    start = re.search(r"^16\\\. Test plan and acceptance criteria", text, re.M)
    end = re.search(r"^17\\\. Team roles", text, re.M)
    if start is None or end is None:
        raise SystemExit("Could not find blueprint section 16.")
    rows = [m.groups() for m in ROW.finditer(text[start.start() : end.start()])]
    if len(rows) != 24:
        raise SystemExit(f"Expected 24 scenarios T01 to T24 in the blueprint, found {len(rows)}.")
    return rows  # type: ignore[return-value]


def pytest_output(*args: str) -> str:
    result = subprocess.run(  # noqa: S603
        [sys.executable, "-m", "pytest", "-o", "addopts=", "-p", "no:cacheprovider", *args],
        cwd=BACKEND,
        capture_output=True,
        text=True,
        check=False,
    )
    return result.stdout


def collect() -> list[str]:
    lines = pytest_output("--collect-only", "-q").splitlines()
    return [line for line in lines if line.startswith("tests/") and "::" in line]


def run_summary() -> str:
    last = [line for line in pytest_output("-q").splitlines() if line.strip()][-1]
    return last.strip()


def frontend_tests() -> dict[str, int]:
    """Per-file test counts from Vitest's own JSON report (so it.each is counted correctly)."""
    npx = shutil.which("npx")
    if npx is None or not (ROOT / "frontend" / "node_modules").is_dir():
        return {}
    with tempfile.TemporaryDirectory() as folder:
        report = Path(folder) / "report.json"
        subprocess.run(  # noqa: S603
            [npx, "vitest", "run", "--reporter=json", f"--outputFile={report}"],
            cwd=ROOT / "frontend",
            capture_output=True,
            check=False,
        )
        if not report.is_file():
            return {}
        data = json.loads(report.read_text(encoding="utf-8"))
    counts: dict[str, int] = {}
    for suite in data["testResults"]:
        name = Path(suite["name"]).resolve().relative_to(ROOT).as_posix()
        counts[name] = len(suite["assertionResults"])
    return dict(sorted(counts.items()))


def module_summary(path: Path) -> str:
    text = path.read_text(encoding="utf-8")
    match = re.match(r'\s*"""(.+?)"""', text, re.S)
    return " ".join(match.group(1).split()) if match else ""


def build(summary: str | None) -> str:
    nodeids = collect()
    names = [(n.split("::")[0], n.split("::")[1].split("[")[0]) for n in nodeids]
    by_scenario: dict[str, list[str]] = defaultdict(list)
    per_file: dict[str, int] = defaultdict(int)
    for file, name in dict.fromkeys(names):
        per_file[file] += 1
        match = TEST_ID.match(name)
        if match:
            by_scenario[match.group(1)].append(f"`{Path(file).name}::{name}`")
    front = frontend_tests()
    frontend_line = (
        f"- Frontend: **{sum(front.values())} tests** in {len(front)} files (Vitest)."
        if front
        else "- Frontend: run `npm test` in `frontend/` (Vitest)."
    )
    lines = [
        "# Test cases",
        "",
        "Generated by `python scripts/gen_test_cases.py`. Do not edit by hand.",
        "",
        "Test-case deliverable for StudyRoute (sandbox, synthetic data). Every scenario in",
        "blueprint section 16 (T01 to T24) is implemented by at least one automated test, and",
        "`backend/tests/test_blueprint_coverage.py` fails if one is missing.",
        "",
        f"- Backend: **{len(nodeids)} tests** in {len(per_file)} files"
        + (f". Last run: `{summary}`." if summary else "."),
        frontend_line,
        "",
        "```bash",
        "cd backend  && pytest -q",
        "cd frontend && npm test",
        "python -m app.scripts.demo_flow   # end-to-end demo against a running API",
        "```",
        "",
        "## Blueprint scenarios T01 to T24",
        "",
        "| ID | Scenario | Expected result | Area | Implemented by |",
        "|----|----------|-----------------|------|----------------|",
    ]
    for ident, scenario, expected, area in blueprint_scenarios():
        tests = "<br>".join(by_scenario.get(ident, ["**MISSING**"]))
        lines.append(f"| {ident} | {scenario} | {expected} | {area} | {tests} |")
    lines += [
        "",
        "## All backend test files",
        "",
        "| File | Tests | Covers |",
        "|------|-------|--------|",
    ]
    for file in sorted(per_file):
        lines.append(f"| `{file}` | {per_file[file]} | {module_summary(BACKEND / file)} |")
    lines += ["", "## Frontend test files", "", "| File | Tests |", "|------|-------|"]
    for file, count in front.items():
        lines.append(f"| `{file}` | {count} |")
    return "\n".join(lines) + "\n"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--no-run", action="store_true", help="collect only, do not run the tests")
    args = parser.parse_args()
    text = build(None if args.no_run else run_summary())
    OUT.write_text(text, encoding="utf-8")
    missing = text.count("**MISSING**")
    print(f"Wrote {OUT.relative_to(ROOT)} ({missing} scenario(s) without a test).")
    return 1 if missing else 0


if __name__ == "__main__":
    sys.exit(main())
