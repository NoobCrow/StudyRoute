DAYS = ["Mon", "Tue", "Wed", "Thu", "Fri", "Sat", "Sun"]


def clean_name(code: str, raw: str) -> str:
    if code in NAME_FIXES:
        return NAME_FIXES[code]
    return raw.replace("&", "and").replace("St.", "Saint").strip()


def _locale(language: str, code: str) -> Locale | None:
    try:
        return Locale.parse(f"{language}_{code}")
    except (ValueError, UnknownLocaleError):
        return None


def weekend_for(code: str, languages: dict) -> list[str]:
    """CLDR weekend for the territory, found through its most spoken language's locale."""
    spoken = languages.get(code, {})
    for language in sorted(spoken, key=lambda name: -spoken[name].get("population_percent", 0)):
        locale = _locale(language, code)
        if locale is not None:
            start, end = locale.weekend_start, locale.weekend_end
            return [DAYS[(start + step) % 7] for step in range(((end - start) % 7) + 1)]
    return ["Sat", "Sun"]


def build() -> tuple[dict[str, dict], set[str]]:
    names = Locale("en").territories
    languages = get_global("territory_languages")
    codes = {c for c in names if len(c) == 2 and c.isalpha() and c not in NOT_COUNTRIES} | set(
        EXTRA_CODES
    )
    codes.discard(HOME)
    directory: dict[str, dict] = {}
    for code in sorted(codes):
        currencies = get_territory_currencies(code, start_date=TODAY, end_date=TODAY)
        currency = CURRENCY_FIXES.get(code) or (currencies[0] if len(currencies) == 1 else None)
        if currency is None:
            sys.exit(
                f"No single current currency for {code}: {currencies}. Add it to CURRENCY_FIXES."
            )
        name = EXTRA_CODES.get(code) or clean_name(code, names[code])
        directory[code] = {
            "name": name,
            "currency": currency,
            "weekend": weekend_for(code, languages),
        }
    return directory, {d["currency"] for d in directory.values()}


def rate_table(currencies: set[str]) -> dict[str, str]:
    missing = sorted(c for c in currencies - EXPLICIT_RATES if c not in UNITS_PER_USD)
    if missing:
        sys.exit(f"No invented rate for: {missing}. Add them to UNITS_PER_USD.")
    quantum = Decimal("0.000001")
    return {
        currency: str(
            (USD_BDT / Decimal(UNITS_PER_USD[currency])).quantize(quantum, rounding=ROUND_HALF_UP)
        )
        for currency in sorted(currencies - EXPLICIT_RATES)
    }


# Keys are quoted because an unquoted NO (Norway) is read by YAML as the boolean false.
def yaml_scalar(value: str) -> str:
    return json.dumps(value, ensure_ascii=False)


def render_rules(directory: dict[str, dict], rates: dict[str, str]) -> str:
    lines = [MARKER, "countries:", "  directory:", "    value:"]
    for code, row in directory.items():
        weekend = ", ".join(row["weekend"])
        lines.append(
            f'      "{code}": {{name: {yaml_scalar(row["name"])}, currency: {row["currency"]}, weekend: [{weekend}]}}'
        )
    lines += [
        "    kind: regulatory",
        "    verified: false",
        '    source_url: "https://cldr.unicode.org/"',
        f'    last_checked: "{TODAY.isoformat()}"',
        '    note: "Every country as a sandbox destination. Names, currencies and weekends come from Unicode CLDR '
        "through Babel and are not checked against each country's banks. Public holidays are not loaded for "
        'these countries. Indicative. Confirm with your AD bank."',
        "  rates:",
        "    value:",
    ]
    lines += [f'      "{currency}": "{rate}"' for currency, rate in rates.items()]
    lines += [
        "    kind: synthetic",
        "    verified: true",
        '    note: "Synthetic mid-market BDT per 1 unit, invented for the sandbox. Not a live feed and not a forecast. '
        'A rule in fx.mid_rates, when it exists, wins."',
        "  restricted:",
        "    value: [CU, IR, KP, SY]",
        "    kind: regulatory",
        "    verified: false",
        '    source_url: "https://example.org/replace-with-bangladesh-bank-restricted-destinations"',
        f'    last_checked: "{TODAY.isoformat()}"',
        '    note: "Destinations the sandbox will not quote, because banks often refuse them. This list is a '
        'placeholder from public sanctions news, not legal advice. Confirm with your AD bank."',
        "",
    ]
    return "\n".join(lines)


def render_currencies(currencies: set[str]) -> str:
    exponents = {c: get_currency_precision(c) for c in sorted(currencies | {"BDT", "JPY"})}
    body = ", ".join(f'"{c}": {e}' for c, e in exponents.items())
    wrapped: list[str] = []
    line = "   "
    for part in body.split(", "):
        piece = f" {part},"
        if len(line) + len(piece) > 100:
            wrapped.append(line)
            line = "   "
        line += piece
    wrapped.append(line)
    return (
        '"""Minor-unit exponents (decimal places) for the currencies the sandbox knows.\n\n'
        "Generated by scripts/gen_countries.py from Unicode CLDR through Babel. Do not edit by hand.\n"
        "Which currencies a destination may use is decided by config/rules.yaml, not here.\n"
        '"""\n\n'
        "from __future__ import annotations\n\n"
        "CURRENCY_EXPONENTS: dict[str, int] = {\n" + "\n".join(wrapped) + "\n}  # fmt: skip\n"
    )


def main() -> None:
    directory, currencies = build()
    rates = rate_table(currencies)
    text = RULES.read_text(encoding="utf-8")
    head = text.split(MARKER)[0].rstrip("\n") + "\n\n"
    RULES.write_text(head + render_rules(directory, rates), encoding="utf-8", newline="\n")
    CURRENCIES_PY.write_text(render_currencies(currencies), encoding="utf-8", newline="\n")
    print(f"{len(directory)} countries, {len(currencies)} currencies, {len(rates)} generated rates")


if __name__ == "__main__":
    main()
