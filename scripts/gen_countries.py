"""Regenerate the destination-country data: every country can be a payment destination.

Writes two files:
  config/rules.yaml                   the `countries:` section at the end (replaced between markers)
  backend/app/engine/currencies.py    ISO 4217 minor-unit exponents for every currency in use

Names, currencies, minor-unit digits and weekends come from Unicode CLDR through Babel.
Babel is a DEVELOPMENT tool for this script only; it is not a runtime dependency:

    pip install babel
    python scripts/gen_countries.py

Exchange rates are INVENTED for the sandbox (units per 1 USD below, against a synthetic
USD rate of 122 BDT). They are not a live feed and not a forecast. Everything generated here
is marked verified: false where it states a regulatory-looking fact (weekends, restrictions).
"""

