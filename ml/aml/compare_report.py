"""Turn the model comparison (submission/evidence/ai_risk_model_comparison.json) into a readable page.

    ml/.venv/Scripts/python ml/aml/compare_report.py

Writes docs/AI_RISK_MODELS.md. Nothing here is typed by hand: every number comes from the JSON that
`compare.py` wrote, so the page and the evidence cannot disagree.
"""

from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SOURCE = ROOT / "submission" / "evidence" / "ai_risk_model_comparison.json"
OUT = ROOT / "docs" / "AI_RISK_MODELS.md"


def pct(value: float, digits: int = 1) -> str:
    return f"{100 * value:.{digits}f}%"


def main() -> None:
    report = json.loads(SOURCE.read_text(encoding="utf-8"))
    rows = report["models"]
    lines = [
        "# Which model for the risk score? Every model, the same data, the same time split",
        "",
        "Generated by `ml/aml/compare_report.py` from `submission/evidence/ai_risk_model_comparison.json`",
        "(written by `ml/aml/compare.py`). Do not edit by hand. Data: IBM's public synthetic transactions",
        "(`docs/AI_RISK.md`). Nothing here is real people or real payments.",
        "",
        "## How the comparison was run",
        "",
        "* **One split for everyone, by time.** Each model learns from the first 60% of the timeline. Its",
        "  own settings (tree depth, class weight, number of epochs) are chosen on the **tuning** period (the",
        "  next 20%) by average precision. The last 20%, the **test** period, is never used to choose",
        "  anything.",
        "* **Two sets of inputs.** `8` = the inputs the shipped model uses. `13` = those 8 plus 5 more",
        "  household-history inputs that StudyRoute could compute from its own payment table: new receivers",
        "  paid in the last 24 hours and 7 days, payments to the same receiver in the last 24 hours, how soon the",
        "  same receiver was paid again, and how this amount compares with the previous one. Neither set sees",
        "  the payment channel, the currencies, the time of day or how many payments a receiver gets.",
        "* **The routing rule is the desk's.** The bands are cut on the tuning period: `HIGH` is the top 0.1% of",
        '  scores and `MEDIUM` the next 0.4%; "medium or high" is what sends a payment to a person.',
        "  The best-F1 point uses a threshold chosen on the tuning period.",
        "* **Which one to ship is decided from the tuning column.** The test column is the report. The flagged",
        "  payments are rare (1,797 in the test period), so differences of about 0.02 in average precision",
        "  between neighbouring models are within the noise.",
        "",
        "## All results, best on the tuning period first",
        "",
        'AP = average precision (random order scores 0.0018). "Top 1%" = share of all flagged payments found',
        "in the model's top 1%. P = precision, R = recall, Acc = accuracy, on the test period.",
        "",
        "| Model | Kind | Inputs | Tuning AP | **Test AP** | Test ROC | Top 1% | Top 5% | Medium+High: P / R / Acc | Best F1: P / R / Acc | First payments AP |",
        "|---|---|---:|---:|---:|---:|---:|---:|---|---|---:|",
    ]
    for r in rows:
        t, u = r["tuning"], r["test"]
        mh, bf = u["medium_or_high"], u["best_f1_point"]
        lines.append(
            f"| {r['model']} | {r['kind']} | {r['inputs']} | {t['average_precision']:.3f} | "
            f"**{u['average_precision']:.3f}** | {u['roc_auc']:.3f} | {pct(u['found_in_top_1_percent'])} | "
            f"{pct(u['found_in_top_5_percent'])} | {pct(mh['precision'])} / {pct(mh['recall'])} / {pct(mh['accuracy'], 2)} | "
            f"{pct(bf['precision'])} / {pct(bf['recall'])} / {pct(bf['accuracy'], 2)} | {u['first_payments_average_precision']:.3f} |"
        )
    learned = [r for r in rows if r["kind"] != "rule"]
    best = learned[0]
    by_test = max(learned, key=lambda r: r["test"]["average_precision"])
    lines += [
        "",
        "## What the table says",
        "",
        f"* **Best on the tuning period:** {best['model']} on {best['inputs']} inputs (tuning AP "
        f"{best['tuning']['average_precision']:.3f}, test AP {best['test']['average_precision']:.3f}).",
        f"* **Highest test AP:** {by_test['model']} on {by_test['inputs']} inputs "
        f"({by_test['test']['average_precision']:.3f}). If this is not the same model, the gap is within the noise.",
        "* **No model comes near 90% precision and 90% recall together.** The best-F1 columns show the best",
        "  balance each one found. The data and its limits are discussed in `docs/AI_RISK.md`.",
        "* **Accuracy is above 99% for every model that flags few payments, and means nothing**: answering",
        '  "not flagged" every time scores 99.82%.',
        "",
        "## Reproduce",
        "",
        "```bash",
        "ml/.venv/Scripts/python ml/aml/compare.py          # all models, about 20 minutes",
        "ml/.venv/Scripts/python ml/aml/compare_report.py   # this page",
        "```",
        "",
    ]
    with open(OUT, "w", encoding="utf-8", newline="\n") as handle:
        handle.write("\n".join(lines))
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
